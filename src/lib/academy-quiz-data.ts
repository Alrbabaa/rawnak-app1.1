export function getQuizForLesson(video: BeautyVideo): QuizQuestion[] {
  return CURATED_LESSON_QUIZZES[video.id] || [];
}

/** A lesson only has a quiz when questions were curated for that exact
 * video. Category/general fallbacks looked plausible but tested unrelated
 * knowledge, especially for newly imported YouTube videos. */
export function hasQuizForLesson(video: BeautyVideo): boolean {
  return getQuizForLesson(video).length > 0;
}
